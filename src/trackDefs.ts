/**
 * Named closed-circuit control points (XZ meters). First point ≈ start/finish;
 * CatmullRom closed=true closes the loop. Keep self-clearance ≳30m and corner
 * radii ≳13.5 so a 14m road never overlaps.
 *
 * Path rule: prefer star-shaped polar / smooth superellipse / rounded-rect loops
 * (`buildPolarLoop`) so the racing ribbon never crosses itself. Avoid hand-sketched
 * S-bays that pinch below ~30m centerline clearance. Yard Drift and biome courses with `underpass: true` are intentional self-crossing courses.
 *
 * SF join rule: put start/finish on a straight (or gentle curve) with several
 * evenly spaced control points wrapping the loop so Catmull-Rom tangents match
 * entering/leaving t≈0 — no reverse-bump or kink at the join.
 */
export type TrackDef = {
  id: string;
  name: string;
  /** Control points as [x, z] pairs in world meters. */
  points: readonly (readonly [number, number])[];
  /**
   * Visual biome for this course (forest / coast / alpine / …).
   * See src/biomes.ts — defaults to forest if omitted.
   */
  biome?: string;
  /** Intentional self-crossings use yard-drift underpass grades (first visit = under). */
  underpass?: boolean;
};

