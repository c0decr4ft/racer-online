/**
 * Build a simple closed loop from a positive polar radius function r(θ).
 * Star-shaped curves from the origin never self-intersect — preferred for new courses.
 * Always validate Catmull-Rom samples for min clearance ≳30m and corner radii ≳13.5.
 */
export function buildPolarLoop(
  n: number,
  rFn: (theta: number) => number,
  rot = 0,
): [number, number][] {
  const pts: [number, number][] = [];
  for (let i = 0; i < n; i++) {
    const th = (i / n) * Math.PI * 2 + rot;
    const r = rFn(th);
    pts.push([Math.cos(th) * r, Math.sin(th) * r]);
  }
  return pts;
}

